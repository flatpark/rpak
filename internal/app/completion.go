package app

import (
	"fmt"
	"io"
)

const completionUsage = `Usage: rpak completion bash|zsh|fish

Prints the shell completion script for rpak. rpak completes its own
commands and options; everything it passes through to flatpak is
completed by flatpak, so what is offered is what will run.

To install it:
  zsh    rpak completion zsh > ~/.zfunc/_rpak
         with fpath=(~/.zfunc $fpath) before compinit in ~/.zshrc
         (any directory in $fpath will do), or in ~/.zshrc after compinit:
         source <(rpak completion zsh)
  bash   in ~/.bashrc: source <(rpak completion bash)
  fish   rpak completion fish > ~/.config/fish/completions/rpak.fish

With alias flatpak=rpak, zsh completes flatpak with rpak's completion;
bash needs "complete -o nospace -F __rpak flatpak" as well.
`

// The scripts are flatpak's (completion/_flatpak, completion/flatpak and
// completion/flatpak.fish in flatpak 1.18) calling "rpak complete", with
// these fixes:
//   - zsh: the cursor is counted on the words before the current one, as
//     on the line passed with it; flatpak's count runs past the cursor,
//     which is wrong when completing in the middle of the line. After an
//     option with "=", the candidates are values, so the part up to the
//     "=" is set aside (compset) for them to match.
//   - bash: works without the bash-completion package (_get_cword).
//   - fish: the cursor is relative to the command, not the whole buffer,
//     and values are put after the "--option=" of the current token.

const zshCompletion = `#compdef rpak
# zsh completion for rpak, generated by "rpak completion zsh".
# Put it in a directory in $fpath as _rpak, or source it after compinit.

_rpak() {
  emulate -L zsh

  local index
  (( index = ${#${(j: :)words[1,CURRENT-1]}} + 1 + $#PREFIX ))

  local resp=($(command rpak complete "$words" $index "$words[CURRENT]" 2>/dev/null))

  local opt_expl arg_expl
  _description options opt_expl option
  _description arguments arg_expl argument

  [[ $words[CURRENT] == -*=* ]] && compset -P '*='

  local match
  for match in $resp; do
    case $match in
      __FLATPAK_FILE) _files;;
      __FLATPAK_BUNDLE_FILE) _path_files -g '*.flatpak';;
      __FLATPAK_BUNDLE_OR_REF_FILE) _path_files -g '*.flatpak(|ref)';;
      __FLATPAK_DIR) _path_files -/;;
      -*=) compadd $opt_expl[@] -S "" -- $match;;
      -*) compadd $opt_expl[@] -- $match;;
      *) compadd $arg_expl[@] -- $match;;
    esac
  done
}

if [[ $funcstack[1] == _rpak ]]; then
  _rpak "$@"
else
  compdef _rpak rpak
fi
`

const bashCompletion = `# bash completion for rpak, generated by "rpak completion bash".
# Use it with: source <(rpak completion bash)

[ -z "$BASH_VERSION" ] && return

__rpak() {
    local IFS=$'\n'
    local cur
    local -a RES
    if declare -F _get_cword >/dev/null; then
        cur=$(_get_cword :)
    else
        cur=${COMP_WORDS[COMP_CWORD]}
    fi
    readarray -t RES < <(command rpak complete "${COMP_LINE}" "${COMP_POINT}" "${cur}" 2>/dev/null)

    COMPREPLY=()
    local res
    local -a COMPGEN_OPTS
    local -a REPLIES
    for res in "${RES[@]}"; do
        if [[ $res == "__FLATPAK_FILE" ]]; then
            COMPGEN_OPTS=('-f')
        elif [[ $res == "__FLATPAK_BUNDLE_FILE" ]]; then
            COMPGEN_OPTS=('-f' '-X' '!*.flatpak')
        elif [[ $res == "__FLATPAK_BUNDLE_OR_REF_FILE" ]]; then
            COMPGEN_OPTS=('-f' '-X' '!*.flatpak@(|ref)')
        elif [[ $res == "__FLATPAK_DIR" ]]; then
            COMPGEN_OPTS=('-d')
        else
            COMPGEN_OPTS=()
        fi

        if [[ ${#COMPGEN_OPTS[@]} -ne 0 ]]; then
            local CUR
            if [[ $cur == "=" ]]; then
                CUR=""
            else
                CUR="$cur"
            fi
            readarray -t REPLIES < <(compgen "${COMPGEN_OPTS[@]}" -- "${CUR}")
            COMPREPLY+=("${REPLIES[@]}")
        else
            COMPREPLY+=("$res")
        fi
    done
}

complete -o nospace -F __rpak rpak
`

const fishCompletion = `# fish completion for rpak, generated by "rpak completion fish".
# Save it as ~/.config/fish/completions/rpak.fish

function __rpak_complete
    set -l current_cmd (commandline -p)
    set -l current_position (commandline -pC)
    set -l current_token (commandline -ct)
    # After --option=, rpak (like flatpak) prints only the value.
    set -l prefix ""
    if string match -q -- "-*=*" "$current_token"
        set prefix (string replace -r -- '[^=]*$' '' "$current_token")
    end
    command rpak complete "$current_cmd" "$current_position" "$current_token" 2>/dev/null | while read -l fp_sugg
        set -l sugg (string trim -- "$fp_sugg")
        switch "$sugg"
            case __FLATPAK_FILE
                __fish_complete_path "$current_token"
            case __FLATPAK_BUNDLE_FILE
                __fish_complete_suffix "$current_token" '.flatpak'
            case __FLATPAK_BUNDLE_OR_REF_FILE
                __fish_complete_suffix "$current_token" '.flatpak'
                __fish_complete_suffix "$current_token" '.flatpakref'
            case __FLATPAK_DIR
                __fish_complete_directories "$current_token"
            case '*'
                echo "$prefix$sugg"
        end
    end
end

function __rpak_complete_files
    if __fish_seen_subcommand_from run build
        set -l pos_args 0
        for t in (commandline -co)
            if string match -q --invert -- "-*" "$t"
                set pos_args (math "$pos_args+1")
            end
        end
        if test $pos_args -gt 2
            return 0
        end
    end
    return 1
end

complete -c rpak -f -n "not __rpak_complete_files" -a '(__rpak_complete)'
complete -c rpak -n "__rpak_complete_files" -a '(__rpak_complete)'
`

var completionScripts = map[string]string{
	"bash": bashCompletion,
	"zsh":  zshCompletion,
	"fish": fishCompletion,
}

// completionCommand is `rpak completion SHELL`.
func completionCommand(argv []string, stdout, stderr io.Writer) int {
	if len(argv) == 1 {
		switch argv[0] {
		case "-h", "--help":
			fmt.Fprint(stdout, completionUsage)
			return 0
		}
		if script, ok := completionScripts[argv[0]]; ok {
			fmt.Fprint(stdout, script)
			return 0
		}
	}
	fmt.Fprint(stderr, completionUsage)
	return 2
}
